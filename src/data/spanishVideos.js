function listVideos() {
  return VIDEOS.map((row) => ({ ...row, presenter: PRESENTERS[row.programId] }));
}

function getVideo(id) {
  return listVideos().find((row) => row.id === id) || null;
}

function videoForSimulation(simulationId) {
  const direct = listVideos().find((row) => row.simulationId === simulationId);
  if (direct) return direct;
  const { LESSONS } = require("./lawEnforcementUnit1");
  const lesson = LESSONS.find((row) => row.simulationId === simulationId);
  return lesson ? getVideo(lesson.videoId) : null;
}

module.exports = { VIDEOS, PRESENTERS, listVideos, getVideo, videoForSimulation };
